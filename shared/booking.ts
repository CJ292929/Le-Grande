/**
 * Shared booking-request contract.
 *
 * This is the single source of truth for what a "booking request" looks
 * like, validated with the same rules on the client (form) and the server
 * (API route). The Google Apps Script endpoint independently re-validates
 * the same rules in GAS JavaScript (it cannot import this module), so any
 * change here must be mirrored there — see google-apps-script/Code.gs.
 *
 * Guest capacity per unit is UNVERIFIED (see shared/units.ts) — this schema
 * intentionally does not enforce a per-unit guest maximum.
 */
import { z } from "zod";
import { units } from "./units.js";

const UNIT_IDS = units.map((unit) => unit.id) as [string, ...string[]];

/** Name of the honeypot field. Must stay empty; any value marks the submission as spam. */
export const BOOKING_HONEYPOT_FIELD = "companyWebsite" as const;

const MANILA_TIME_ZONE = "Asia/Manila";

/** Today's calendar date (YYYY-MM-DD) in Asia/Manila, computed fresh on every call. */
export function getManilaTodayISO(referenceDate: Date = new Date()): string {
  const formatter = new Intl.DateTimeFormat("en-CA", {
    timeZone: MANILA_TIME_ZONE,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  });
  return formatter.format(referenceDate);
}

const CALENDAR_DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;

/** True only for a real calendar date (rejects e.g. 2026-02-30). */
export function isValidCalendarDateString(value: string): boolean {
  if (!CALENDAR_DATE_PATTERN.test(value)) return false;
  const [year, month, day] = value.split("-").map(Number);
  const date = new Date(Date.UTC(year, month - 1, day));
  return (
    date.getUTCFullYear() === year &&
    date.getUTCMonth() === month - 1 &&
    date.getUTCDate() === day
  );
}

const calendarDateSchema = z
  .string()
  .trim()
  .regex(CALENDAR_DATE_PATTERN, "Use the YYYY-MM-DD format.")
  .refine(isValidCalendarDateString, "Enter a real calendar date.");

/** Cross-field checks shared by the full (server) schema and the client form schema. */
export function bookingCrossFieldRefinement(
  data: { checkIn: string; checkOut: string },
  ctx: z.RefinementCtx
): void {
  if (data.checkOut <= data.checkIn) {
    ctx.addIssue({
      code: "custom",
      path: ["checkOut"],
      message: "Check-out must be after check-in.",
    });
  }
  if (data.checkIn < getManilaTodayISO()) {
    ctx.addIssue({
      code: "custom",
      path: ["checkIn"],
      message: "Check-in can't be in the past.",
    });
  }
}

export const bookingRequestObjectSchema = z
  .object({
    requestId: z.string().uuid(),
    fullName: z.string().trim().min(1, "Enter your full name.").max(120),
    email: z.string().trim().max(254).email("Enter a valid email address."),
    phone: z.string().trim().max(40).optional(),
    unitId: z.enum(UNIT_IDS, { message: "Select a residence." }),
    checkIn: calendarDateSchema,
    checkOut: calendarDateSchema,
    guests: z.number().int().positive().safe(),
    message: z.string().trim().max(1000).optional(),
    [BOOKING_HONEYPOT_FIELD]: z.string().max(200).optional(),
  })
  .strict();

export const bookingRequestSchema = bookingRequestObjectSchema.superRefine(bookingCrossFieldRefinement);

export type BookingRequest = z.infer<typeof bookingRequestSchema>;

/** Validates everything the guest actually types; requestId is generated by the client, not entered. */
export const bookingFormSchema = bookingRequestObjectSchema
  .omit({ requestId: true })
  .superRefine(bookingCrossFieldRefinement);

export type BookingFormValues = z.infer<typeof bookingFormSchema>;

/** The subset of a validated booking request that is meaningful to forward/store — excludes the honeypot. */
export type BookingRequestPayload = Omit<BookingRequest, typeof BOOKING_HONEYPOT_FIELD>;

export function stripHoneypot(request: BookingRequest): BookingRequestPayload {
  const { [BOOKING_HONEYPOT_FIELD]: _honeypot, ...rest } = request;
  return rest;
}

/**
 * Deterministic JSON (sorted keys) of the fields that define "the same booking
 * request" — used to detect whether a retried requestId still refers to the
 * same payload. Mirrored in google-apps-script/Code.gs (canonicalPayloadString).
 */
export function canonicalPayloadString(payload: BookingRequestPayload): string {
  const ordered: Record<string, string | number> = {
    checkIn: payload.checkIn,
    checkOut: payload.checkOut,
    email: payload.email,
    fullName: payload.fullName,
    guests: payload.guests,
    message: payload.message ?? "",
    phone: payload.phone ?? "",
    unitId: payload.unitId,
  };
  return JSON.stringify(ordered);
}
